def get_oblast_for_district(raion_name: str) -> str:
    """Повертає назву області для зазначеного району."""
    if not raion_name:
        return ""
    norm = raion_name.replace("’", "'").replace("`", "'").replace("ʼ", "'").lower()
    norm = norm.replace(" район", "").replace(" р-н", "").strip()
    return DISTRICT_TO_OBLAST_MAP.get(norm, "")
